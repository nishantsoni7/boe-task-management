// The lines the BOE One loader (the logo screen while a page waits) and the
// once-a-day splash on the home page can show.
//
// Every line is either original wording or a well-established fact. A line with
// a person's name on it (`by`) is a quote we are sure about; everything else is
// written here, so nothing is misattributed. Keep each line under MAX_SPLASH_CHARS
// so it fits the loader's three lines on a phone, and add to the END of a list:
// the splash remembers what it has shown by a hash of the text, so editing a line
// makes it count as new, and adding lines never disturbs the rest.
//
// 'news' is not in this file. A headline is fetched (see headlines.ts) and
// stored in the browser; it joins the draw when one is available.

// The kinds, labels and length limit live in kinds.ts (small, always loaded);
// this file is the data and is loaded on demand. Re-exported so callers and
// tests can keep importing everything from one place.
import type { SplashItem, SplashKind } from './kinds'
