// Regenerates docs/app-context/APP_INVENTORY.generated.md from the code itself.
// Facts only (routes, tables, functions, migrations, env names, tests); the
// narrative lives in 01_APP_CONTEXT.md. Run: node scripts/generate-app-inventory.mjs
// Pass --check to fail (exit 1) when the committed file is out of date.
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const out = path.join(root, 'docs', 'app-context', 'APP_INVENTORY.generated.md')
const rel = (p) => path.relative(root, p).split(path.sep).join('/')

function walk(dir, filter, acc = []) {
  if (!fs.existsSync(dir)) return acc
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name)
    if (e.isDirectory()) walk(p, filter, acc)
    else if (filter(p)) acc.push(p)
  }
  return acc
}
const read = (p) => fs.readFileSync(p, 'utf8')
const git = (...a) => execFileSync('git', a, { cwd: root, encoding: 'utf8' }).trim()
const uniq = (a) => [...new Set(a)].sort()

const L = []
const h = (n, t) => L.push('', `${'#'.repeat(n)} ${t}`, '')

// ── Pages ───────────────────────────────────────────────────────────────────
const appDir = path.join(root, 'src', 'app')
const pages = walk(appDir, (p) => /[\\/]page\.tsx$/.test(p)).map((p) => '/' + rel(path.dirname(p)).replace(/^src\/app\/?/, '').replace(/\/$/, ''))
const byTop = {}
for (const r of pages) (byTop[r.split('/')[1] || '(root)'] ??= []).push(r)

// ── API routes ──────────────────────────────────────────────────────────────
const apiDir = path.join(appDir, 'api')
const apis = walk(apiDir, (p) => /[\\/]route\.ts$/.test(p)).map((p) => {
  const src = read(p)
  const methods = uniq([...src.matchAll(/export\s+(?:async\s+)?function\s+(GET|POST|PUT|PATCH|DELETE)\b/g)].map((m) => m[1]))
  return { route: '/' + rel(path.dirname(p)).replace(/^src\/app\//, ''), methods }
})
const apiByTop = {}
for (const a of apis) (apiByTop[a.route.split('/')[2] ?? '(root)'] ??= []).push(a)

// ── Migrations / DB objects ─────────────────────────────────────────────────
const migDir = path.join(root, 'supabase', 'migrations')
const migs = fs.readdirSync(migDir).filter((f) => f.endsWith('.sql')).sort()
const tables = new Map()
const functions = new Set()
const buckets = new Set()
const enums = new Set()
for (const f of migs) {
  const sql = read(path.join(migDir, f)).replace(/^s*--.*$/gm, '')
  for (const m of sql.matchAll(/create\s+table\s+(?:if\s+not\s+exists\s+)?(?:public\.)?"?([a-z0-9_]+)"?\s*\(/gi)) if (!tables.has(m[1])) tables.set(m[1], f)
  for (const m of sql.matchAll(/create\s+(?:or\s+replace\s+)?function\s+(?:public\.)?"?([a-z0-9_]+)"?\s*\(/gi)) functions.add(m[1])
  for (const m of sql.matchAll(/create\s+type\s+(?:public\.)?"?([a-z0-9_]+)"?\s+as\s+enum/gi)) enums.add(m[1])
  for (const m of sql.matchAll(/storage\.buckets[^;]*?values\s*\(\s*'([^']+)'/gi)) buckets.add(m[1])
  for (const m of sql.matchAll(/insert\s+into\s+storage\.buckets[^;]*?\(\s*(?:[a-z_,\s]+)\)\s*values\s*\(\s*'([^']+)'/gi)) buckets.add(m[1])
}
const dropped = new Set()
for (const f of migs) for (const m of read(path.join(migDir, f)).replace(/^s*--.*$/gm, '').matchAll(/drop\s+table\s+(?:if\s+exists\s+)?(?:public\.)?"?([a-z0-9_]+)"?/gi)) dropped.add(m[1])

// ── Env vars, tests, deps ───────────────────────────────────────────────────
const srcFiles = walk(path.join(root, 'src'), (p) => /\.(ts|tsx)$/.test(p)).concat(walk(path.join(root, 'scripts'), (p) => /\.(ts|mjs)$/.test(p)))
const env = {}
for (const p of srcFiles) for (const m of read(p).matchAll(/process\.env\.([A-Z][A-Z0-9_]+)/g)) env[m[1]] = (env[m[1]] ?? 0) + 1
const tests = srcFiles.filter((p) => /\.test\.(ts|tsx|mjs)$/.test(p))
const libDirs = fs.readdirSync(path.join(root, 'src', 'lib'), { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name)
const pkg = JSON.parse(read(path.join(root, 'package.json')))

// ── Compose ─────────────────────────────────────────────────────────────────
L.push('# BOE Task Management — Generated Inventory', '', '> GENERATED by `node scripts/generate-app-inventory.mjs`. Do not edit by hand.',
  '> Facts are read from the code at the commit named below; the narrative is in `01_APP_CONTEXT.md`.')
h(2, 'Snapshot')
L.push(`- Commit: \`${git('rev-parse', '--short', 'HEAD')}\` — ${git('log', '-1', '--format=%s')}`,
  `- Commits on this branch: ${git('rev-list', '--count', 'HEAD')}`,
  `- Pages (\`page.tsx\`): ${pages.length}   API routes (\`route.ts\`): ${apis.length}`,
  `- Migrations: ${migs.length} (first \`${migs[0]}\`, latest \`${migs.at(-1)}\`)`,
  `- Tables ever created: ${tables.size} (dropped at some point: ${dropped.size})   SQL functions: ${functions.size}   Enums: ${enums.size}`,
  `- Test files: ${tests.length}   Next.js ${pkg.dependencies.next}, React ${pkg.dependencies.react}`)
h(2, 'Latest 25 commits')
L.push(...git('log', '-25', '--format=- `%h` %ad %s', '--date=short').split('\n'))
h(2, 'Pages by top-level area')
for (const k of Object.keys(byTop).sort()) L.push(`- **${k}** (${byTop[k].length}): ${byTop[k].sort().map((r) => '`' + r + '`').join(', ')}`)
h(2, 'API routes by area')
for (const k of Object.keys(apiByTop).sort()) L.push(`- **${k}** (${apiByTop[k].length}): ${apiByTop[k].sort((a, b) => a.route.localeCompare(b.route)).map((a) => '`' + a.route.replace('/api/' + k, '') + (a.methods.length ? ' [' + a.methods.join(',') + ']' : '') + '`').join(', ')}`)
h(2, 'Library folders (src/lib)')
for (const d of libDirs.sort()) {
  const files = walk(path.join(root, 'src', 'lib', d), (p) => /\.(ts|tsx)$/.test(p))
  L.push(`- \`src/lib/${d}\` — ${files.filter((p) => !/\.test\./.test(p)).length} source, ${files.filter((p) => /\.test\./.test(p)).length} test`)
}
h(2, 'Environment variable names read by the code')
L.push('Names only — values live in `.env.local` (git-ignored) and in Vercel. See `03_BACKUP_AND_RECOVERY.md`.', '')
for (const [k, v] of Object.entries(env).sort()) L.push(`- \`${k}\` (${v} reads)`)
h(2, 'Storage buckets named in migrations')
L.push(buckets.size ? [...buckets].sort().map((b) => '`' + b + '`').join(', ') : '(none detected)')
h(2, 'Tables (first migration that created each; * = dropped later)')
for (const [t, f] of [...tables].sort((a, b) => a[0].localeCompare(b[0]))) L.push(`- \`${t}\`${dropped.has(t) ? '*' : ''} — ${f.slice(0, 14)}`)
h(2, 'Last 30 migrations')
for (const f of migs.slice(-30)) L.push(`- \`${f}\``)
h(2, 'All SQL function names')
L.push([...functions].sort().map((f) => '`' + f + '`').join(', '))
L.push('')

const text = L.join('\n')
if (process.argv.includes('--check')) {
  const have = fs.existsSync(out) ? read(out) : ''
  const strip = (s) => s.replace(/^- Commit:.*$/m, '').replace(/^- Commits on this branch:.*$/m, '').replace(/## Latest 25 commits[\s\S]*?\n## Pages/, '## Pages')
  if (strip(have) !== strip(text)) { console.error('APP_INVENTORY.generated.md is stale — run node scripts/generate-app-inventory.mjs'); process.exit(1) }
  console.log('inventory up to date')
} else {
  fs.mkdirSync(path.dirname(out), { recursive: true })
  fs.writeFileSync(out, text)
  console.log(`wrote ${rel(out)} (${text.length} bytes)`)
}
